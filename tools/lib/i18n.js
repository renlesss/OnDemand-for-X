'use strict';
/*
 * Locale files -> the script that ships with the extension.
 *
 *   locales/<code>.json   flat { key: text } maps. English (en.json) is the reference: every other
 *                         file must have exactly the same keys. "_name" is the language's own name
 *                         (shown in the language picker) and "_dir" is "ltr" or "rtl".
 *
 * validate() returns a list of problems (empty = fine); source() returns the text of i18n.js.
 */
const fs = require('fs');
const path = require('path');

const REFERENCE = 'en';
const CODE = /^[a-z]{2,3}(-[A-Z]{2})?$/;
// longest text each kind of label may have, so a longer translation cannot break the small chip and buttons
const LIMITS = [
  [/^st_/, 30],            // the status chip on a phone
  [/^(more|fetching)$/, 34], // the big button
  [/^(gateTitle|copy|copied|close|diagRefresh|langAuto|language|settings)$/, 34],
  [/./, 160],
];
const limitFor = (key) => LIMITS.find(([re]) => re.test(key))[1];

function loadLocales(dir) {
  const out = {};
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith('.json')) continue;
    const code = file.slice(0, -5);
    out[code] = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
  }
  return out;
}

const tokens = (text) => (String(text).match(/\{[A-Za-z0-9_]+\}/g) || []).sort().join(',');

function validate(locales) {
  const problems = [];
  const ref = locales[REFERENCE];
  if (!ref) return [`${REFERENCE}.json (the reference language) is missing`];
  const refKeys = Object.keys(ref);
  for (const [code, table] of Object.entries(locales)) {
    const at = `${code}.json`;
    if (!CODE.test(code)) problems.push(`${at}: the file name is not a language code`);
    if (!table || typeof table !== 'object' || Array.isArray(table)) { problems.push(`${at}: not an object`); continue; }
    const keys = Object.keys(table);
    for (const k of refKeys) if (!keys.includes(k)) problems.push(`${at}: missing key "${k}"`);
    for (const k of keys) if (!refKeys.includes(k)) problems.push(`${at}: unknown key "${k}"`);
    if (table._dir !== 'ltr' && table._dir !== 'rtl') problems.push(`${at}: "_dir" must be "ltr" or "rtl"`);
    for (const k of keys) {
      const v = table[k];
      if (typeof v !== 'string' || !v.trim()) { problems.push(`${at}: "${k}" is empty or not text`); continue; }
      if (v !== v.trim()) problems.push(`${at}: "${k}" has spaces at its ends`);
      if (/[<>]/.test(v)) problems.push(`${at}: "${k}" contains < or > (texts are plain text, never markup)`);
      // eslint-disable-next-line no-control-regex
      if (/[\u0000-\u001f\u007f]/.test(v)) problems.push(`${at}: "${k}" contains a control character`);
      if (!k.startsWith('_') && v.length > limitFor(k)) problems.push(`${at}: "${k}" is ${v.length} characters, the limit is ${limitFor(k)}`);
      if (code !== REFERENCE && ref[k] !== undefined && tokens(v) !== tokens(ref[k])) problems.push(`${at}: "${k}" has different {placeholders} than ${REFERENCE}.json`);
    }
  }
  return problems;
}

function source(locales) {
  const codes = Object.keys(locales).sort();
  const names = {};
  const t = {};
  for (const code of codes) {
    const { _name: name, _dir: dir, ...rest } = locales[code];
    names[code] = name;
    t[code] = { dir, ...rest };
  }
  // the reference language first inside each table keeps the output stable and diffs small
  return `/* generated by tools/build.js from locales/*.json — do not edit */\nglobalThis.__xodI18n = ${JSON.stringify({ order: codes, names, t })};\n`;
}

module.exports = { loadLocales, validate, source, REFERENCE, limitFor };
